#!/usr/bin/env node
/**
 * Compile the descriptions, and keep them honest against the product.
 *
 *   node specs/generate.ts            write `specs/generated/*.ts` from the text
 *   node specs/generate.ts --check    fail when the text and the product disagree
 *   node specs/generate.ts --draft    print a line for every call the text does not have
 *
 * The text is the source of truth (`specs/server/http.txt`, `specs/cli/cli.txt`, plus the
 * resources both share in `specs/common.txt`). Nothing here writes a description: a new route
 * or command makes `--check` fail, and `--draft` prints the line a person then types in. That
 * is the same division syzkaller keeps between its descriptions, `syz-extract` and
 * `syz-sysgen` — the product publishes the interface, the text says what it means.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { compile, parseFile, ParseError, type Program } from "./syz.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "generated");

interface SurfaceRoute {
  method: string;
  path: string;
}

interface SurfaceEndpoint {
  method: string;
  path: string;
  fields: unknown[];
}

interface Surface {
  routes: SurfaceRoute[];
  endpoints: SurfaceEndpoint[];
}

interface TreeCommand {
  path: string[];
  args: { name: string; required: boolean; variadic: boolean }[];
  options: { name: string; flags: string; takesValue: boolean; mandatory: boolean }[];
}

const problems: string[] = [];
const notes: string[] = [];

function problem(message: string): void {
  problems.push(message);
}

/** `include "…"` is textual: the included file's declarations join the including program. */
function expand(file: string, seen: string[] = []): string {
  const resolved = path.resolve(file);
  if (seen.includes(resolved)) throw new Error(`include cycle: ${[...seen, resolved].join(" -> ")}`);
  const dir = path.dirname(resolved);
  return fs
    .readFileSync(resolved, "utf8")
    .split("\n")
    .map((line) => {
      const m = /^\s*include\s+"([^"]+)"\s*(?:#.*)?$/.exec(line);
      if (!m) return line;
      return expand(path.join(dir, m[1]!), [...seen, resolved]);
    })
    .join("\n");
}

function load(entry: string): Program {
  return compile(parseFile(expand(entry), path.relative(here, entry)));
}

const SERVER = path.join(here, "server", "http.txt");
const CLI = path.join(here, "cli", "cli.txt");

function generated(program: Program): Map<string, string> {
  const files = new Map<string, string>();

  const routes = program.server.map((call) => ({
    id: call.id,
    method: call.method,
    path: call.path,
    pathArgs: call.pathArgs,
    queryArgs: call.queryArgs,
    body: call.body,
  }));
  files.set(
    path.join(outDir, "server.ts"),
    [
      "// Code generated by specs/generate.ts from specs/server/http.txt. DO NOT EDIT.",
      "",
      'import type { RouteDescr } from "../types.js";',
      "",
      "export const ROUTES: readonly RouteDescr[] = [",
      ...routes.map((route) => `  ${JSON.stringify(route)},`),
      "];",
      "",
    ].join("\n"),
  );

  const commands = program.cli.map((call) => ({
    id: call.id,
    path: call.path,
    args: call.args,
    options: call.options,
    textOption: call.textOption,
    exits: call.exits,
    together: call.together,
  }));
  files.set(
    path.join(outDir, "cli.ts"),
    [
      "// Code generated by specs/generate.ts from specs/cli/cli.txt. DO NOT EDIT.",
      "",
      'import type { CommandDescr } from "../types.js";',
      "",
      "export const COMMANDS: readonly CommandDescr[] = [",
      ...commands.map((command) => `  ${JSON.stringify(command)},`),
      "];",
      "",
    ].join("\n"),
  );

  const resources = [...program.resources.keys()].sort();
  files.set(
    path.join(outDir, "resources.ts"),
    [
      "// Code generated by specs/generate.ts from specs/common.txt. DO NOT EDIT.",
      "",
      "export const RESOURCES: ReadonlySet<string> = new Set([",
      ...resources.map((name) => `  ${JSON.stringify(name)},`),
      "]);",
      "",
    ].join("\n"),
  );

  return files;
}

/** The surface's own call list: route metadata plus the client's endpoints. */
function surfaceCalls(): Map<string, string[]> {
  const surface = JSON.parse(fs.readFileSync(path.join(here, "surface.json"), "utf8")) as Surface;
  const calls = new Map<string, string[]>();
  for (const route of [...surface.routes, ...surface.endpoints]) {
    // The client's own endpoints carry their query in the path (`…/balance?provider=`); the
    // description names the route and its knobs separately, so only the path is an id.
    const path = route.path.split("?")[0]!;
    const id = `${route.method} ${path}`;
    if (calls.has(id)) continue;
    calls.set(id, [...path.matchAll(/:([A-Za-z]+)(?:\{[^}]*\})?/g)].map((m) => m[1]!));
  }
  return calls;
}

async function commandTree(): Promise<TreeCommand[] | null> {
  const built = path.join(here, "..", "build", "tests", "fuzzers", "specs", "cli", "tree.js");
  if (!fs.existsSync(built)) {
    notes.push(`cli drift not checked: ${path.relative(path.join(here, ".."), built)} is not built yet`);
    return null;
  }
  // The built tree imports the product's `@prismshadow/*` specifiers, which resolve only in the
  // compiled layout. Registering the same hook the fuzz processes use keeps this call runnable on
  // its own — `node specs/generate.ts --check`, no flags.
  await import(pathToFileURL(path.join(here, "..", "resolve-hook.mjs")).href);
  const module = (await import(pathToFileURL(built).href)) as { commandTree(): TreeCommand[] };
  return module.commandTree();
}

function describeCommand(command: TreeCommand): string {
  const args = command.args.map((arg) => `${arg.name} ${arg.variadic ? "array[string]" : "string"}${arg.required ? "" : " opt"}`);
  const options = command.options.map((option) => `${option.flags} ${option.takesValue ? "string" : "bool"}${option.mandatory ? "" : " opt"}`);
  return `${command.path.join(".")}(${[...args, ...options].join(", ")})`;
}

/** Every call the text describes must exist; every call the product has must be accounted for. */
function checkServer(program: Program): void {
  const surface = surfaceCalls();
  const described = new Set(program.server.map((call) => call.id));
  const skipped = new Set(program.skips.filter((skip) => skip.leg === "server").map((skip) => skip.id));
  const missing = [...surface.keys()].filter((id) => !described.has(id) && !skipped.has(id));
  const unknown = [...described, ...skipped].filter((id) => !surface.has(id));
  for (const id of missing) problem(`server: ${id} is neither described nor skipped`);
  for (const id of unknown) problem(`server: ${id} is not a route the product declares`);
  for (const call of program.server) {
    const slots = surface.get(call.id);
    if (slots === undefined) continue;
    const named = call.pathArgs.map((arg) => arg.name);
    if (slots.join(",") !== named.join(",")) {
      problem(`server: ${call.id} declares [${named.join(", ")}], the path has [${slots.join(", ")}]`);
    }
  }
}

function checkCli(program: Program, tree: TreeCommand[]): void {
  const described = new Map(program.cli.map((call) => [call.id, call]));
  const skipped = new Set(program.skips.filter((skip) => skip.leg === "cli").map((skip) => skip.id));
  const known = new Set(tree.map((command) => command.path.join(" ")));
  for (const command of tree) {
    const id = command.path.join(" ");
    if (!described.has(id) && !skipped.has(id)) problem(`cli: ${id} is neither described nor skipped`);
  }
  for (const id of [...described.keys(), ...skipped]) {
    if (!known.has(id)) problem(`cli: ${id} is not a command the product declares`);
  }
  for (const command of tree) {
    const call = described.get(command.path.join(" "));
    if (call === undefined) continue;
    const args = command.args.map((arg) => `${arg.name}:${arg.required ? "req" : "opt"}:${arg.variadic ? "many" : "one"}`);
    const mine = call.args.map((arg) => `${arg.name}:${arg.required ? "req" : "opt"}:${arg.variadic ? "many" : "one"}`);
    if (args.join(",") !== mine.join(",")) {
      problem(`cli: ${call.id} declares [${mine.join(", ")}], the tree has [${args.join(", ")}]`);
    }
    const options = command.options.map((option) => `${option.flags}:${option.takesValue ? "value" : "bool"}:${option.mandatory ? "req" : "opt"}`);
    const mineOptions = call.options.map((option) => `${option.flags}:${option.takesValue ? "value" : "bool"}:${option.mandatory ? "req" : "opt"}`);
    if (options.join(",") !== mineOptions.join(",")) {
      problem(`cli: ${call.id} declares options [${mineOptions.join(", ")}], the tree has [${options.join(", ")}]`);
    }
  }
}

function draft(program: Program, tree: TreeCommand[] | null): void {
  const surface = surfaceCalls();
  const described = new Set([
    ...program.server.map((call) => call.id),
    ...program.skips.filter((skip) => skip.leg === "server").map((skip) => skip.id),
  ]);
  for (const [id, slots] of surface) {
    if (described.has(id)) continue;
    const args = slots.map((slot) => `${slot} id`).join(", ");
    console.log(`${id}(${args})`);
  }
  if (tree !== null) {
    const cliKnown = new Set([
      ...program.cli.map((call) => call.id),
      ...program.skips.filter((skip) => skip.leg === "cli").map((skip) => skip.id),
    ]);
    for (const command of tree) {
      if (cliKnown.has(command.path.join(" "))) continue;
      console.log(describeCommand(command));
    }
  }
}

async function main(): Promise<void> {
  const check = process.argv.includes("--check");
  const drafting = process.argv.includes("--draft");

  let server: Program;
  let cli: Program;
  try {
    server = load(SERVER);
    cli = load(CLI);
  } catch (error) {
    if (error instanceof ParseError) {
      console.error(`[specs] ${error.message}`);
      process.exit(1);
    }
    throw error;
  }

  if (drafting) {
    // Both legs: a route is drafted from the surface, a command from the tree, and each leg's
    // own skips are what tells the two apart.
    draft(merge(server, cli), await commandTree());
    return;
  }

  const files = generated(merge(server, cli));
  let stale = false;
  for (const [file, text] of files) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (current === text) continue;
    stale = true;
    if (check) problem(`${path.relative(here, file)} is out of date; run node specs/generate.ts`);
    else {
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, text);
      console.log(`[specs] wrote ${path.relative(here, file)}`);
    }
  }

  if (check) {
    checkServer(server);
    const tree = await commandTree();
    if (tree !== null) checkCli(cli, tree);
  }

  for (const note of notes) console.error(`[specs] ${note}`);
  if (problems.length > 0) {
    for (const message of problems) console.error(`[specs] ${message}`);
    process.exit(1);
  }
  console.log(
    `[specs] ${server.server.length} routes, ${cli.cli.length} commands, ` +
      `${server.skips.length + cli.skips.length} skipped${stale ? "" : ", generated files current"}`,
  );
}

/** The two legs share one resource table; the emitted files are per leg. */
function merge(server: Program, cli: Program): Program {
  return {
    resources: new Map([...server.resources, ...cli.resources]),
    types: server.types,
    structs: server.structs,
    unions: server.unions,
    server: server.server,
    cli: cli.cli,
    skips: [...server.skips, ...cli.skips],
  };
}

await main();
